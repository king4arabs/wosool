import assert from 'node:assert/strict'
import { spawn } from 'node:child_process'
import { chromium } from 'playwright'
const origin = 'http://127.0.0.1:18088'
const app = spawn(process.execPath, ['node_modules/next/dist/bin/next', 'start', '-H', '127.0.0.1', '-p', '18088'], { stdio: ['ignore', 'pipe', 'pipe'] })
let log = ''; app.stdout.on('data', v => log += v); app.stderr.on('data', v => log += v)
let browser
try {
  for (let i = 0; i < 150 && !log.includes('Ready'); i++) await new Promise(r => setTimeout(r, 100))
  assert.ok(log.includes('Ready'), log)
  browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || undefined })
  for (const locale of ['ar', 'en']) for (const width of [320, 390, 768, 1440]) {
    const ar = locale === 'ar'
    const context = await browser.newContext({ viewport: { width, height: 1000 }, reducedMotion: 'no-preference' })
    await context.addInitScript(l => localStorage.setItem('wosool-locale', l), locale)
    const page = await context.newPage(); const errors = []; page.on('pageerror', e => errors.push(e.message))
    await context.route('**/*', route => {
      const url = new URL(route.request().url()); if (url.origin !== origin) return route.abort()
      if (url.pathname.startsWith('/api/')) return route.fulfill({ json: { data: [], meta: { total: 0, last_page: 1 } } })
      return route.continue()
    })
    await page.goto(origin + '/partners', { waitUntil: 'networkidle' })
    const section = page.locator('#partner-ecosystem')
    await section.getByRole('heading', { name: ar ? 'فرص الشراكة' : 'Partnership opportunities' }).waitFor()
    await section.locator('[data-visit-ready="true"]').waitFor()
    const strip = section.locator('[data-partner-marquee]')
    const ids = () => strip.locator('[data-partner-copy="primary"] a[tabindex="0"]').evaluateAll(links => links.map(link => link.dataset.partnerId))
    const original = await ids()
    assert.equal(new Set(original).size, 80)
    assert.equal(await strip.locator('img').count(), 160)
    const failed = await strip.locator('img').evaluateAll(images => images.filter(img => !img.complete || !img.naturalWidth).map(img => img.getAttribute('src')))
    assert.deepEqual(failed, [], 'Every logo must load')
    const track = strip.locator(':scope > div')
    const transform = () => track.evaluate(el => new DOMMatrixReadOnly(getComputedStyle(el).transform).m41)
    const before = await transform(); await strip.hover(); await page.waitForTimeout(600); const after = await transform()
    assert.ok(after > before, 'Artwork keeps moving physically right on hover in both languages')
    assert.equal(await track.evaluate(el => getComputedStyle(el).animationPlayState), 'running')
    assert.ok(await strip.locator('img').evaluateAll(images => images.every(img => getComputedStyle(img).objectFit === 'contain')))
    assert.equal(await section.locator('#partner-category, [role="group"], details, summary').count(), 0, 'Category and duplicate website directory are removed')
    await section.getByRole('searchbox').fill('NEOM')
    assert.deepEqual(await ids(), ['neom'], 'English names work in both languages')
    assert.equal(await track.evaluate(el => el.getBoundingClientRect().width >= el.parentElement.clientWidth * 2), true, 'Short results still fill both loop copies')
    assert.equal(await strip.locator('a[aria-hidden="true"][tabindex="0"]').count(), 0, 'Decorative repeats cannot receive focus')
    await page.emulateMedia({ reducedMotion: 'reduce' })
    assert.equal(await track.evaluate(el => getComputedStyle(el).animationName), 'none')
    assert.equal(await strip.locator('a:visible').count(), 1, 'Reduced motion presents each matching logo once')
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await section.getByRole('searchbox').fill('')
    assert.deepEqual(await ids(), original)

    const nextLocale = ar ? 'en' : 'ar'
    if (width < 1024) await page.getByRole('button', { name: ar ? 'فتح قائمة التنقل' : 'Open navigation menu', exact: true }).click()
    await page.locator('header select:visible').selectOption(nextLocale)
    if (width < 1024) await page.getByRole('button', { name: nextLocale === 'ar' ? 'إغلاق قائمة التنقل' : 'Close navigation menu', exact: true }).click()
    await section.getByRole('heading', { name: nextLocale === 'ar' ? 'فرص الشراكة' : 'Partnership opportunities' }).waitFor()
    assert.deepEqual(await ids(), original, 'Language changes preserve the visit’s order')
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false)
    await section.screenshot({ path: `/tmp/partner-ecosystem-${locale}-${width}.png` })
    await page.reload({ waitUntil: 'networkidle' })
    await section.locator('[data-visit-ready="true"]').waitFor()
    const reloaded = await ids()
    assert.notDeepEqual(reloaded, original, 'A full reload creates a fresh visit order')
    await page.locator('#become-partner a').click()
    await page.waitForURL('**/contact')
    await page.locator('a[href="/partners"]:visible').first().click()
    await page.waitForURL('**/partners')
    await section.locator('[data-visit-ready="true"]').waitFor()
    assert.notDeepEqual(await ids(), reloaded, 'Returning through client navigation creates a fresh order')
    assert.deepEqual(errors, [])
    console.log(`PASS ${locale}/${width}: 80 logos, fresh visit order, stable search and language, search, rightward motion, seamless short results, responsive layout, reduced motion`)
    await context.close()
  }
} finally { await browser?.close(); app.kill('SIGTERM') }
